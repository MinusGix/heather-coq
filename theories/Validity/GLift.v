(** * Lifting validity lemmas to global weakenings

    The tactics the fundamental theorem's cases use (moved here from
    [Fundamental] so that the [Wf] eliminator's [nth] lemmas can lift the
    validity lemmas they compose, M15a). *)
From DeLaM.Validity Require Export Vec.
From DeLaM.LogRel Require IWfAux.

(** ** Lifting to global weakenings

    Each case is proved at an arbitrary global weakening [γ : G' ≤ G] of
    its rule's global context: the hypotheses at [G] are weakened, [⟦γ⟧]
    is pushed through the syntax, and the case's lemma applies at [G']. *)

Ltac gl_weaken :=
  match goal with Hγ : gwk_ok ?γ ?G' ?G, HG' : [ ⊢ ?G' ] |- _ =>
    repeat match goal with
    | H : VTyG G _ _ _ _ |- _ =>
        pose proof (VTyG_gwk H Hγ); pose proof (VTyG_loc (VTyG_gwk H Hγ)); clear H
    | H : VTmG G _ _ _ _ _ |- _ =>
        pose proof (VTmG_gwk H Hγ); pose proof (VTmG_loc (VTmG_gwk H Hγ)); clear H
    | H : wf_ctx G _ _ |- _ => pose proof (gwa_ctx Hγ HG' H); clear H
    | H : wf_ty G _ _ _ _ |- _ => pose proof (gwa_ty Hγ HG' H); clear H
    | H : wf_tm G _ _ _ _ _ |- _ => pose proof (gwa_tm Hγ HG' H); clear H
    | H : eq_ty G _ _ _ _ _ |- _ => pose proof (gwa_eqty Hγ HG' H); clear H
    | H : eq_tm G _ _ _ _ _ _ |- _ => pose proof (gwa_eqtm Hγ HG' H); clear H
    | H : in_ctx ?Γ0 _ _ _ |- _ =>
        lazymatch Γ0 with gwa _ _ => fail | _ => pose proof (in_ctx_gwa _ _ _ _ γ H); clear H end
    | H : lequiv (gL G) _ _ |- _ => apply (lequiv_weaken _ _ _ _ (proj1 Hγ)) in H
    | H : lwf (gL G) _ |- _ => apply (lwf_weaken _ _ _ (proj1 Hγ)) in H
    end
  end.

(** [nth] and [elim_Wf]'s induction hypothesis (M15a). *)
Lemma gwa_tmNth γ l T k cs i : (tmNth l T k cs i)⟦γ⟧ = tmNth l T⟦γ⟧ k⟦γ⟧ cs⟦γ⟧ i⟦γ⟧.
Proof. destruct γ; cbn [gwa]; [reflexivity | apply gren_tmNth ..]. Qed.
Lemma gwa_wfIH γ l l' A N M c a cs :
  (wfIH l l' A N M c a cs)⟦γ⟧ = wfIH l l' A⟦γ⟧ N⟦γ⟧ M⟦γ⟧ c⟦γ⟧ a⟦γ⟧ cs⟦γ⟧.
Proof. destruct γ; cbn [gwa]; [reflexivity | apply gren_wfIH ..]. Qed.

(** [dnth], [elim_IWf], its family and induction hypothesis (M17b). *)
Lemma gwa_elimIWf γ l li l' X A N Ot C M c m t :
  (tmElimIWf l li l' X A N Ot C M c m t)⟦γ⟧ =
  tmElimIWf l li l' X⟦γ⟧ A⟦γ⟧ N⟦γ⟧ Ot⟦γ⟧ C⟦γ⟧ M⟦γ⟧ c⟦γ⟧ m⟦γ⟧ t⟦γ⟧.
Proof. now destruct γ. Qed.
Lemma gwa_tmDNth γ l n F cs i : (tmDNth l n F cs i)⟦γ⟧ = tmDNth l n⟦γ⟧ F⟦γ⟧ cs⟦γ⟧ i⟦γ⟧.
Proof. destruct γ; cbn [gwa]; [reflexivity | apply gren_tmDNth ..]. Qed.
Lemma gwa_iwfIH γ l li l' X A N Ot C M c a cs :
  (iwfIH l li l' X A N Ot C M c a cs)⟦γ⟧ = iwfIH l li l' X⟦γ⟧ A⟦γ⟧ N⟦γ⟧ Ot⟦γ⟧ C⟦γ⟧ M⟦γ⟧ c⟦γ⟧ a⟦γ⟧ cs⟦γ⟧.
Proof. destruct γ; cbn [gwa]; [reflexivity | apply gren_iwfIH ..]. Qed.
Lemma gwa_iwfFam γ l li X A N Ot C a :
  (iwfFam l li X A N Ot C a)⟦γ⟧ = iwfFam l li X⟦γ⟧ A⟦γ⟧ N⟦γ⟧ Ot⟦γ⟧ C⟦γ⟧ a⟦γ⟧.
Proof. destruct γ; cbn [gwa]; [reflexivity | apply gren_iwfFam ..]. Qed.

(** [gl_push]: generated by [tools/gen_push.py] from its lemma list. *)
